"""Run each query in sql/analysis.sql and write the results to a Markdown report."""
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def main():
    text = (ROOT / "sql" / "analysis.sql").read_text(encoding="utf-8")
    sections = ["# SQL analysis results\n", "Generated by `src/run_analysis.py` from `sql/analysis.sql`.\n"]
    with sqlite3.connect(ROOT / "data" / "olist.db") as con:
        for block in text.split("-- name: ")[1:]:
            title, query = block.split("\n", 1)
            frame = pd.read_sql_query(query, con)
            header = "| " + " | ".join(frame.columns) + " |"
            divider = "|" + "---|" * len(frame.columns)
            rows = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in row) + " |"
                    for row in frame.itertuples(index=False)]
            sections.append(f"\n## {title}\n\n" + "\n".join([header, divider, *rows]) + "\n")
    report = "".join(sections)
    (ROOT / "reports" / "sql_analysis.md").write_text(report, encoding="utf-8")
    print(report)


if __name__ == "__main__":
    main()
